static int in(const range_t *table, int n, unsigned long cp)
{
	int lo = 0, hi = n - 1;

	if (cp < table[0].first || cp > table[n - 1].last) return 0;
	while (lo <= hi) {
		int mid = (lo + hi) / 2;
		if (cp < table[mid].first) hi = mid - 1;
		else if (cp > table[mid].last) lo = mid + 1;
		else return 1;
	}
	return 0;
}

/* The columns of code point CP: 0, 1 or 2 (control characters are the
 * display's business, not this table's) */
int char_width(unsigned long cp)
{
	if (cp < 0x0300) return 1;
	if (in(zero, (int) (sizeof zero / sizeof *zero), cp)) return 0;
	if (in(wide, (int) (sizeof wide / sizeof *wide), cp)) return 2;
	return 1;
}

/* (fe-char-width code-point) */
int fe_char_width(long cp)
{
	return cp < 0 ? 1 : char_width((unsigned long) cp);
}

/* The code point at offset OFF of BP, whose first byte is not ASCII, read
 * across the gap if need be; a malformed sequence is U+FFFD (one column) */
unsigned long code_point_at(buffer_t *bp, point_t off)
{
	char_t *p = ptr(bp, off);
	int n = utf8_size(*p), k;
	unsigned long cp = *p & (n == 2 ? 0x1F : n == 3 ? 0x0F : 0x07);

	if (n == 1) return 0xFFFD;
	for (k = 1; k < n; k++) {
		if (off + k >= document_size(bp)) return 0xFFFD;
		p = ptr(bp, off + k);
		if ((*p & 0xC0) != 0x80) return 0xFFFD;
		cp = (cp << 6) | (*p & 0x3F);
	}
	return cp;
}
